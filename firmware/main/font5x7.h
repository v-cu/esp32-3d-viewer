/*
 * font5x7.h - minimal 5x7 column font for the HUD (digits, "fps", a few symbols)
 * Each glyph = 5 columns, bit 0 = top row.
 */
#pragma once
#include <stdint.h>

static inline const uint8_t *font5x7_glyph(char c)
{
    static const uint8_t digits[10][5] = {
        {0x3E, 0x51, 0x49, 0x45, 0x3E}, {0x00, 0x42, 0x7F, 0x40, 0x00}, {0x42, 0x61, 0x51, 0x49, 0x46},
        {0x21, 0x41, 0x45, 0x4B, 0x31}, {0x18, 0x14, 0x12, 0x7F, 0x10}, {0x27, 0x45, 0x45, 0x45, 0x39},
        {0x3C, 0x4A, 0x49, 0x49, 0x30}, {0x01, 0x71, 0x09, 0x05, 0x03}, {0x36, 0x49, 0x49, 0x49, 0x36},
        {0x06, 0x49, 0x49, 0x29, 0x1E},
    };
    static const uint8_t f[5] = {0x08, 0x7E, 0x09, 0x01, 0x02};
    static const uint8_t p[5] = {0x7C, 0x14, 0x14, 0x14, 0x08};
    static const uint8_t s[5] = {0x48, 0x54, 0x54, 0x54, 0x20};
    static const uint8_t pct[5] = {0x23, 0x13, 0x08, 0x64, 0x62};
    static const uint8_t dot[5] = {0x00, 0x60, 0x60, 0x00, 0x00};
    static const uint8_t dash[5] = {0x08, 0x08, 0x08, 0x08, 0x08};
    static const uint8_t slash[5] = {0x20, 0x10, 0x08, 0x04, 0x02};
    static const uint8_t blank[5] = {0, 0, 0, 0, 0};
    if (c >= '0' && c <= '9') return digits[c - '0'];
    switch (c) {
    case 'f': return f;
    case 'p': return p;
    case 's': return s;
    case '%': return pct;
    case '.': return dot;
    case '-': return dash;
    case '/': return slash;
    default: return blank;
    }
}
